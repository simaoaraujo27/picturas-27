"""Build a readable inventory from recorded evaluation metadata."""

import hashlib
import json
import xml.etree.ElementTree as ET
from pathlib import Path

from .results import is_framework_test_summary


BASELINE = "052310226c51fa57a17101c7bd1ad795674aac95"
LEGACY_BASELINE = "ab3ae9cf8efcfa444e9599f8e291551c5930c289"
INITIAL_REFACTORED = "914476a92b4e4bc51f925ba2c4ef9468988e57c8"
REFACTORED_MILESTONES = (
    "9976985af4990e398bbbc6fdbe5d4ec97e61e11e",
    "1fe42ba9d1a22535bc121e37125e5b5f713455a2",
    "3df66ae1baa507d07db2c53dcde4d301232e428e",
)
MARKER = "<!-- Generated by python -m evaluation index; do not edit manually. -->"
LEGACY_MARKER = "<!-- Generated by python -m fase2.evaluation index; do not edit manually. -->"


def _read(path: Path) -> dict | None:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return value if isinstance(value, dict) else None


def _role(meta: dict) -> str:
    if meta.get("source_kind") == "working_tree_snapshot":
        return "local snapshot"
    if meta.get("role") in {"baseline", "refactored", "unclassified"}:
        return meta["role"]
    commit = meta.get("resolved_commit")
    if commit in {BASELINE, LEGACY_BASELINE}:
        return "baseline"
    if commit in (*REFACTORED_MILESTONES, INITIAL_REFACTORED):
        return "refactored"
    return "other commit / unclassified"


def _category(root: Path, name: str) -> tuple[str, str]:
    data = _read(root / name / "summary.json")
    if data is None:
        return "unavailable", "unrecorded"
    if name == "static":
        return data.get("status", "unavailable"), "not applicable"
    if name == "contracts":
        counts = [item.get(key, {}) for item in data.get("contracts", [])
                  for key in ("junit_result", "verification_junit_result") if item.get(key)]
        passed = sum(int(c.get("tests", 0)) - int(c.get("failures", 0)) - int(c.get("errors", 0))
                     - int(c.get("skipped", 0)) for c in counts)
        failed = sum(int(c.get("failures", 0)) for c in counts)
        errors = sum(int(c.get("errors", 0)) for c in counts)
        return (f"{data.get('verification_status', 'unavailable')} "
                f"({passed} passed, {failed} failed, {errors} errors)"), data.get("suite_sha256", "unrecorded")
    suites = data.get("suites", [])
    if suites and not all("counts" in item for item in suites):
        status = data.get("verification_status", "unavailable")
        identities = {item.get("id", "unknown"): item.get("test_files", {}) for item in suites}
        version = hashlib.sha256(json.dumps(identities, sort_keys=True).encode()).hexdigest()
        return f"{status} (counts unrecorded)", version
    passed = sum(int(item.get("counts", {}).get("passed", item.get("counts", {}).get("pass", 0))) for item in suites)
    failed = sum(int(item.get("counts", {}).get("failed", item.get("counts", {}).get("fail", 0))) for item in suites)
    identities = {item.get("id", "unknown"): item.get("test_files", {}) for item in suites}
    version = hashlib.sha256(json.dumps(identities, sort_keys=True).encode()).hexdigest() if identities else "unrecorded"
    return f"{data.get('verification_status', 'unavailable')} ({passed} passed, {failed} failed)", version


def collect_rows(root: Path) -> list[dict]:
    rows = []
    for path in root.rglob("metadata.json"):
        meta = _read(path)
        if meta is None or "requested_categories" not in meta:
            continue
        run = path.parent
        commit = meta.get("resolved_commit") or meta.get("base_commit") or "unrecorded"
        for category in meta["requested_categories"]:
            result, suite = _category(run, category)
            rows.append({"role": _role(meta), "commit": commit, "date": meta.get("started_at_utc", "unrecorded"),
                         "run_id": meta.get("run_id", "unrecorded"), "category": category,
                         "suite": suite, "result": result, "framework": meta.get("framework", {}).get("code_sha256", "unrecorded"),
                         "path": run.relative_to(root).as_posix()})
    for path in root.rglob("summary*.json"):
        data = _read(path)
        if data is None or not is_framework_test_summary(data):
            continue
        counts = data.get("counts", data)
        failed = counts.get("failures", counts.get("failed", "?"))
        passed = (int(counts["tests"]) - int(counts.get("failures", 0))
                  - int(counts.get("errors", 0)) - int(counts.get("skipped", 0))) if "tests" in counts else counts.get("passed", "?")
        date = data.get("executed_at_utc", "unrecorded")
        if date == "unrecorded" and data.get("junit"):
            try:
                suite = ET.parse(path.parent / data["junit"]).getroot().find("testsuite")
                date = suite.get("timestamp", "unrecorded") if suite is not None else "unrecorded"
            except (OSError, ET.ParseError):
                pass
        rows.append({"role": "framework", "commit": data.get("base_commit", data.get("source_head", "unrecorded")),
                     "date": date, "run_id": data.get("run_id", path.stem),
                     "category": "framework tests", "suite": data.get("suite_sha256", "unrecorded"),
                     "result": f"{passed} passed, {failed} failed",
                     "framework": data.get("framework", {}).get("code_sha256", "unrecorded"),
                     "path": path.relative_to(root).as_posix()})
    return sorted(rows, key=lambda row: (row["date"], row["path"], row["category"]))


def build_index(root: Path, output: Path | None = None) -> Path:
    root = root.expanduser().resolve()
    if not root.is_dir():
        raise ValueError(f"Results root does not exist: {root}")
    output = (output or root / "INDEX.md").expanduser().resolve()
    if output.exists() and not output.read_text(encoding="utf-8").startswith((MARKER, LEGACY_MARKER)):
        raise ValueError(f"Refusing to replace a non-generated file: {output}")
    lines = [MARKER, "# Evaluation runs", "",
             "Roles come from metadata identities. A snapshot's base commit is provenance, not its evaluated source.",
             "Historical framework summaries without a suite digest are marked `unrecorded`.", "",
             "| Role | Commit / base commit | Date (UTC) | Run ID | Category | Suite SHA-256 | Result | Framework SHA-256 | Evidence |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for row in collect_rows(root):
        values = [row[key] for key in ("role", "commit", "date", "run_id", "category", "suite", "result", "framework")]
        values = [str(value).replace("|", "\\|") for value in values]
        lines.append("| " + " | ".join(values + [f"[result]({row['path']})"]) + " |")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output
